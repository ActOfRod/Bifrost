static inline uint8_t bf_gmul(uint8_t a, uint8_t b) {
    uint8_t r = 0;
    while (b) { if (b & 1) r ^= a; a = (uint8_t)((a << 1) ^ ((a & 0x80) ? 0x1B : 0)); b >>= 1; }
    return r;
}
static inline void bf_aese(BfVec *d, const BfVec *n) {
    BfVec s, r;
    for (int i = 0; i < 16; i++) s.b[i] = d->b[i] ^ n->b[i];
    for (int row = 0; row < 4; row++)
        for (int col = 0; col < 4; col++) r.b[row + 4 * col] = bf_aes_sbox[s.b[row + 4 * ((col + row) & 3)]];
    *d = r;
}
static inline void bf_aesd(BfVec *d, const BfVec *n) {
    BfVec s, r;
    for (int i = 0; i < 16; i++) s.b[i] = d->b[i] ^ n->b[i];
    for (int row = 0; row < 4; row++)
        for (int col = 0; col < 4; col++) r.b[row + 4 * col] = bf_aes_isbox[s.b[row + 4 * ((col - row + 4) & 3)]];
    *d = r;
}
static inline void bf_aes_mix(BfVec *d, const BfVec *n, const uint8_t m[4]) {
    BfVec r;
    for (int col = 0; col < 4; col++)
        for (int row = 0; row < 4; row++) {
            uint8_t v = 0;
            for (int k = 0; k < 4; k++) v ^= bf_gmul(n->b[k + 4 * col], m[(k - row + 4) & 3]);
            r.b[row + 4 * col] = v;
        }
    *d = r;
}
static inline void bf_aesmc(BfVec *d, const BfVec *n) { static const uint8_t m[4] = {2, 3, 1, 1}; bf_aes_mix(d, n, m); }
static inline void bf_aesimc(BfVec *d, const BfVec *n) { static const uint8_t m[4] = {14, 11, 13, 9}; bf_aes_mix(d, n, m); }

static inline uint32_t bf_rol32(uint32_t v, int s) { return (v << s) | (v >> (32 - s)); }
static inline uint32_t bf_sha_ror(uint32_t v, int s) { return (v >> s) | (v << (32 - s)); }

static inline void bf_sha1_hash(BfVec *d, const BfVec *n, const BfVec *m, int kind) {
    uint32_t x[4] = {d->s[0], d->s[1], d->s[2], d->s[3]}, y = n->s[0];
    for (int e = 0; e < 4; e++) {
        uint32_t t;
        if (kind == 0) t = ((x[2] ^ x[3]) & x[1]) ^ x[3];
        else if (kind == 1) t = x[1] ^ x[2] ^ x[3];
        else t = (x[1] & x[2]) | ((x[1] | x[2]) & x[3]);
        y = y + bf_rol32(x[0], 5) + t + m->s[e];
        x[1] = bf_rol32(x[1], 30);
        uint32_t ny = x[3];
        x[3] = x[2]; x[2] = x[1]; x[1] = x[0]; x[0] = y; y = ny;
    }
    for (int i = 0; i < 4; i++) d->s[i] = x[i];
}
static inline void bf_sha1c(BfVec *d, const BfVec *n, const BfVec *m) { bf_sha1_hash(d, n, m, 0); }
static inline void bf_sha1p(BfVec *d, const BfVec *n, const BfVec *m) { bf_sha1_hash(d, n, m, 1); }
static inline void bf_sha1m(BfVec *d, const BfVec *n, const BfVec *m) { bf_sha1_hash(d, n, m, 2); }
static inline void bf_sha1su0(BfVec *d, const BfVec *n, const BfVec *m) {
    BfVec r;
    r.d[0] = d->d[1]; r.d[1] = n->d[0];
    r.d[0] ^= d->d[0] ^ m->d[0]; r.d[1] ^= d->d[1] ^ m->d[1];
    *d = r;
}
static inline void bf_sha1h(BfVec *d, const BfVec *n) { uint32_t v = bf_rol32(n->s[0], 30); d->d[0] = v; d->d[1] = 0; }
static inline void bf_sha1su1(BfVec *d, const BfVec *n) {
    uint32_t t[4] = {d->s[0] ^ n->s[1], d->s[1] ^ n->s[2], d->s[2] ^ n->s[3], d->s[3]};
    BfVec r;
    r.s[0] = bf_rol32(t[0], 1); r.s[1] = bf_rol32(t[1], 1); r.s[2] = bf_rol32(t[2], 1);
    r.s[3] = bf_rol32(t[3], 1) ^ bf_rol32(t[0], 2);
    *d = r;
}
static inline void bf_sha256_hash(BfVec *out, const BfVec *xv, const BfVec *yv, const BfVec *w, int part1) {
    uint32_t x[4], y[4];
    for (int i = 0; i < 4; i++) { x[i] = xv->s[i]; y[i] = yv->s[i]; }
    for (int e = 0; e < 4; e++) {
        uint32_t chs = ((y[1] ^ y[2]) & y[0]) ^ y[2];
        uint32_t maj = (x[0] & x[1]) | ((x[0] | x[1]) & x[2]);
        uint32_t t = y[3] + (bf_sha_ror(y[0], 6) ^ bf_sha_ror(y[0], 11) ^ bf_sha_ror(y[0], 25)) + chs + w->s[e];
        x[3] = t + x[3];
        y[3] = t + (bf_sha_ror(x[0], 2) ^ bf_sha_ror(x[0], 13) ^ bf_sha_ror(x[0], 22)) + maj;
        uint32_t x3 = x[3], y3 = y[3];
        x[3] = x[2]; x[2] = x[1]; x[1] = x[0]; x[0] = y3;
        y[3] = y[2]; y[2] = y[1]; y[1] = y[0]; y[0] = x3;
    }
    for (int i = 0; i < 4; i++) out->s[i] = part1 ? x[i] : y[i];
}
static inline void bf_sha256h(BfVec *d, const BfVec *n, const BfVec *m) { BfVec x = *d, y = *n; bf_sha256_hash(d, &x, &y, m, 1); }
static inline void bf_sha256h2(BfVec *d, const BfVec *n, const BfVec *m) { BfVec x = *n, y = *d; bf_sha256_hash(d, &x, &y, m, 0); }
static inline void bf_sha256su0(BfVec *d, const BfVec *n) {
    uint32_t t[4] = {d->s[1], d->s[2], d->s[3], n->s[0]};
    for (int e = 0; e < 4; e++) {
        uint32_t v = t[e];
        d->s[e] += bf_sha_ror(v, 7) ^ bf_sha_ror(v, 18) ^ (v >> 3);
    }
}
static inline void bf_sha256su1(BfVec *d, const BfVec *n, const BfVec *m) {
    uint32_t t0[4] = {n->s[1], n->s[2], n->s[3], m->s[0]};
    uint32_t r[4];
    uint32_t t1[2] = {m->s[2], m->s[3]};
    for (int e = 0; e < 4; e++) {
        uint32_t v = e < 2 ? t1[e] : r[e - 2];
        v = bf_sha_ror(v, 17) ^ bf_sha_ror(v, 19) ^ (v >> 10);
        r[e] = v + d->s[e] + t0[e];
    }
    for (int e = 0; e < 4; e++) d->s[e] = r[e];
}
